#!/usr/bin/env python3
"""The roozTrans logo: a white R with 译 ("translate") inside its loop, on navy.

Writes every icon from one definition:
  app/src/main/res/drawable/ic_launcher_fg.xml    adaptive launcher icon foreground
  app/src/main/res/drawable/ic_launcher_mono.xml  themed (monochrome) launcher icon
  app/src/main/res/drawable/ic_bubble.xml         one-colour icon: notification + Quick Settings tile
  app/src/main/res/drawable/ic_bubble_logo.xml    full-colour icon for the floating bubble
  play/graphics/icon-512.png, play/graphics/feature-1024x500.png
Needs fontTools, Pillow and google-chrome (headless, for the PNGs).
Run: python3 play/tools/make-logo.py
"""
import pathlib, subprocess, tempfile
from fontTools.ttLib import TTCollection
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[2]
RES = ROOT / "app/src/main/res"
OUT = ROOT / "play/graphics"
NAVY, ORANGE, WHITE = "#1F1D4D", "#FF8A3D", "#FFFFFF"
CJK = "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc"   # SIL Open Font License

# ---- geometry, in a 100x100 box ----
R_PATH = "M31,79V21H50A19,19 0 0,1 50,59H31M47,59L69,79"   # stem, loop, leg
R_WIDTH = 6.5
YI_BOX = 21.0                # 译 fits inside a square this big ...
YI_CENTRE = (50.0, 40.0)     # ... centred in the R's loop

def yi_path():
    font = TTCollection(CJK).fonts[2]                      # index 2 = Noto Sans CJK SC
    gs = font.getGlyphSet(); name = font.getBestCmap()[ord("译")]
    b = BoundsPen(gs); gs[name].draw(b); x0, y0, x1, y1 = b.bounds
    s = YI_BOX / max(x1 - x0, y1 - y0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    pen = SVGPathPen(gs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
    # font units are y-up: flip, scale and move the glyph centre onto YI_CENTRE
    gs[name].draw(TransformPen(pen, (s, 0, 0, -s, YI_CENTRE[0] - s * cx, YI_CENTRE[1] + s * cy)))
    return pen.getCommands()

YI = yi_path()

def vector(size_dp, view, group, r_col, yi_col):
    """VectorDrawable: `view` = viewport size, `group` = attributes placing the 100-box logo in it."""
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by play/tools/make-logo.py. Edit that script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size_dp}dp" android:height="{size_dp}dp" android:viewportWidth="{view}" android:viewportHeight="{view}">
    <group {group}>
        <path android:strokeColor="{r_col}" android:strokeWidth="{R_WIDTH}" android:strokeLineCap="round" android:strokeLineJoin="round"
            android:pathData="{R_PATH}"/>
        <path android:fillColor="{yi_col}"
            android:pathData="{YI}"/>
    </group>
</vector>
"""

# Launcher: 108dp canvas, only the middle ~66dp is safe from masks, so shrink the logo around the centre.
LAUNCH = 'android:pivotX="50" android:pivotY="50" android:scaleX="0.66" android:scaleY="0.66"'
# Small icons: the logo spans about 28..72 x 18..82, so crop to a 68-unit square around it.
SMALL = 'android:translateX="-16" android:translateY="-16"'

files = {
    RES / "drawable/ic_launcher_fg.xml": vector(108, 100, LAUNCH, WHITE, ORANGE),
    RES / "drawable/ic_launcher_mono.xml": vector(108, 100, LAUNCH, WHITE, WHITE),
    RES / "drawable/ic_bubble.xml": vector(24, 68, SMALL, WHITE, WHITE),
    RES / "drawable/ic_bubble_logo.xml": vector(24, 68, SMALL, WHITE, ORANGE),
}
for p, text in files.items():
    p.write_text(text); print("wrote", p.relative_to(ROOT))

# ---- Play Store PNGs, rendered by headless Chrome ----
def svg_logo(px, r_col=WHITE, yi_col=ORANGE):
    return (f'<svg viewBox="0 0 100 100" width="{px}" height="{px}">'
            f'<path d="{R_PATH}" fill="none" stroke="{r_col}" stroke-width="{R_WIDTH}" stroke-linecap="round" stroke-linejoin="round"/>'
            f'<path d="{YI}" fill="{yi_col}"/></svg>')

ICON = f'<body style="margin:0;background:{NAVY}"><div style="width:512px;height:512px;display:grid;place-items:center">{svg_logo(400)}</div>'
FEATURE = f"""<meta charset="utf-8"><body style="margin:0;background:{NAVY};font-family:'Noto Sans CJK SC',sans-serif;color:#fff">
<div style="width:1024px;height:500px;display:flex;align-items:center;gap:56px;padding-left:72px;box-sizing:border-box">
  <div style="width:320px;height:320px;border-radius:50%;background:rgba(255,255,255,.08);display:grid;place-items:center;flex:none">{svg_logo(300)}</div>
  <div>
    <div style="font-size:92px;font-weight:700;line-height:1.1">roozTrans</div>
    <div style="font-size:46px;font-weight:700;margin-top:14px">English ⇄ <span style="color:{ORANGE}">中文</span></div>
    <div style="font-size:30px;margin-top:26px;color:#D8D6F0;line-height:1.45">Text · photos · your screen<br>Works offline · no ads</div>
  </div>
</div>"""

def render(html, w, h, out):
    with tempfile.TemporaryDirectory() as d:
        page = pathlib.Path(d, "p.html"); page.write_text(html, encoding="utf-8")
        shot = pathlib.Path(d, "s.png")
        subprocess.run(["google-chrome", "--headless=new", "--disable-gpu", "--hide-scrollbars",
                        f"--window-size={w},{h}", f"--screenshot={shot}", page.as_uri()],
                       check=True, capture_output=True)
        Image.open(shot).convert("RGB").crop((0, 0, w, h)).save(out)   # Play wants no alpha
    print("wrote", out.relative_to(ROOT))

render(ICON, 512, 512, OUT / "icon-512.png")
render(FEATURE, 1024, 500, OUT / "feature-1024x500.png")
